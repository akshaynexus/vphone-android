#!/usr/bin/env bash
# Builds libreims_vgpu.a for aarch64-linux-android and installs it as a dist tree QEMU links
# through pkg-config: android/build/out/reims-dist/{lib,lib/pkgconfig,include}.
#
# It builds `reims-vgpu-c` on the Vulkan platform, without SDL or a window system, at the release
# profile; the same build's shared library is linked with -z defs, so every symbol the library
# needs of bionic and of Android's libraries is checked here. The .pc takes its Libs.private from
# rustc (`--print native-static-libs`), as `cargo xtask dist` does.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
# shellcheck source=../env.sh
. "$ROOT/android/env.sh"

OUT=$ROOT/android/build/out/reims-dist
TARGET=aarch64-linux-android
PROFILE=release
export CARGO_TARGET_DIR=$ROOT/android/build/rust
# 16 KiB-page devices: max-page-size on every link this build makes; -z defs refuses an undefined
# symbol at link time rather than at dlopen on the phone.
PAGE_FLAGS=(-Wl,-z,max-page-size=16384 -Wl,-z,common-page-size=16384)
# reims-vgpu-core's guest accesses are written against LSE, LSE2 and RCPC (guest/ptr/raw/aarch64.rs);
# the phones this targets (Snapdragon 8 Gen 3, 8 Elite Gen 5) are ARMv9 and have all three.
RUSTFLAGS_ANDROID="-C target-feature=+lse,+lse2,+rcpc -C link-arg=${PAGE_FLAGS[0]} -C link-arg=${PAGE_FLAGS[1]} -C link-arg=-Wl,-z,defs"
export CARGO_TARGET_AARCH64_LINUX_ANDROID_RUSTFLAGS="$RUSTFLAGS_ANDROID"

cd "$ROOT/reims-vgpu"

BUILD_LOG=$ROOT/android/build/reims-build.log
# reims-vgpu pins its own toolchain (rust-toolchain.toml, a dated nightly since vphone-next4),
# which does not come with the Android target: add it to that toolchain, once.
rustup target list --installed | grep -qx "$TARGET" || rustup target add "$TARGET"
cargo rustc --target "$TARGET" --profile "$PROFILE" -p reims-vgpu-c --lib \
    --no-default-features --features reims-vgpu-c/vulkan \
    -- --print native-static-libs 2>&1 | tee "$BUILD_LOG"

NATIVE_LIBS=$(sed -n 's/.*native-static-libs: //p' "$BUILD_LOG" | tail -n1)
if [ -z "$NATIVE_LIBS" ]; then
    echo "error: rustc printed no native-static-libs" >&2
    exit 1
fi
# rustc's list always carries the runtime's own libraries; the static link adds the page flag.
LIBS_PRIVATE="$NATIVE_LIBS ${PAGE_FLAGS[*]}"

ARTIFACTS=$CARGO_TARGET_DIR/$TARGET/$PROFILE
VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n1)

rm -rf "$OUT"
mkdir -p "$OUT/lib/pkgconfig" "$OUT/include"
cp "$ARTIFACTS/libreims_vgpu_c.a" "$OUT/lib/libreims_vgpu.a"
cp crates/reims-vgpu-c/include/reims_vgpu_android.h "$OUT/include/"
# The installed header gives a host the Android calls too; the header kept in the repository is
# generated by cbindgen and does not know about them.
{
    cat crates/reims-vgpu-c/include/reims_vgpu.h
    printf '\n#ifdef __ANDROID__\n#include "reims_vgpu_android.h"\n#endif\n'
} > "$OUT/include/reims_vgpu.h"

cat > "$OUT/lib/pkgconfig/reims-vgpu.pc" <<EOF
# Written by android/scripts/build-reims.sh.
prefix=\${pcfiledir}/../..
libdir=\${prefix}/lib
includedir=\${prefix}/include

Name: reims-vgpu
Description: The host side of the paravirtualized GPU, for Android
Version: $VERSION
Libs: -L\${libdir} -lreims_vgpu
Libs.private: $LIBS_PRIVATE
Cflags: -I\${includedir}
EOF

# Checks of what was installed: the header compiles, and an object calling the Android API links
# against the archive with the .pc's libraries, at 16 KiB, with no undefined symbol.
CHECK=$ROOT/android/build/reims-link-check
mkdir -p "$CHECK"
cat > "$CHECK/check.c" <<'EOF'
#include "reims_vgpu.h"
void reims_link_check(void *gipa, void *window)
{
    rvg_android_set_vulkan_gipa(gipa);
    rvg_android_set_window(window);
    rvg_android_pointer(0, 0, RVG_WINDOW_BUTTON_LEFT);
}
EOF
"$CC_aarch64_linux_android" -c -fPIC -Wall -Werror -I "$OUT/include" "$CHECK/check.c" -o "$CHECK/check.o"
# shellcheck disable=SC2086
"$CC_aarch64_linux_android" -shared -Wl,-z,defs "${PAGE_FLAGS[@]}" -o "$CHECK/libreims-link-check.so" \
    "$CHECK/check.o" -Wl,--whole-archive "$OUT/lib/libreims_vgpu.a" -Wl,--no-whole-archive $NATIVE_LIBS
NM=$ANDROID_NDK_ROOT/toolchains/llvm/prebuilt/linux-x86_64/bin/llvm-nm
READELF=$ANDROID_NDK_ROOT/toolchains/llvm/prebuilt/linux-x86_64/bin/llvm-readelf
"$NM" -D --defined-only "$CHECK/libreims-link-check.so" | grep ' T rvg_android_pointer$' > /dev/null
ALIGN=$("$READELF" -lW "$CHECK/libreims-link-check.so" | awk '$1 == "LOAD" { print $NF; exit }')
if [ "$ALIGN" != "0x4000" ]; then
    echo "error: load segments are aligned to $ALIGN, not 16 KiB" >&2
    exit 1
fi

echo "reims-vgpu dist: $OUT (Libs.private: $LIBS_PRIVATE)"
ls -l "$OUT/lib/libreims_vgpu.a"
